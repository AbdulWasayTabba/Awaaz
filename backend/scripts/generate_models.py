"""Generates models.py from the Awaaz database schema document.

Usage:  python generate_models.py Awaaz_Database_Schema.md models.py
Reproduces: tables, columns, types, nullability, PKs, single-column FKs,
unique constraints. Does NOT reproduce: RLS policies, check constraints,
views/materialised views, SQL functions, composite FKs (see report).
"""
import re
import sys
from collections import defaultdict

src, out = sys.argv[1], sys.argv[2]
lines = open(src, encoding="utf-8").read().splitlines()

HDR = re.compile(r"^`(\w+)\.(\w+)`(.*)$")
REF = re.compile(r"→ (\w+)\.(\w+)\.(\w+)")

tables = {}          # (schema, name) -> dict
views = []
cur = None
for ln in lines:
    m = HDR.match(ln)
    if m:
        schema, name, rest = m.groups()
        if rest.startswith("view") or rest.startswith("materialised view"):
            views.append(f"{schema}.{name}")
            cur = None
        else:
            cur = {"schema": schema, "name": name, "cols": [], "uniques": []}
            tables[(schema, name)] = cur
        continue
    if cur is None:
        continue
    if ln.startswith("Unique:"):
        for grp in re.findall(r"\(([^)]*)\)", ln):
            cur["uniques"].append([c.strip() for c in grp.split(",")])
        continue
    if ln.startswith("| `"):
        cells = [c.strip() for c in ln.strip().strip("|").split("|")]
        if len(cells) < 5:
            continue
        cells = cells[:4] + ["|".join(cells[4:])]
        name, typ, nul, key, ref = cells
        cur["cols"].append({
            "name": name.strip("`"), "type": typ.strip("`"),
            "nullable": nul == "null", "key": key,
            "refs": REF.findall(ref),
        })
    elif ln.startswith("### ") or ln.startswith("## "):
        cur = None

print(f"parsed {len(tables)} tables, {len(views)} views")

# primary keys per table
pk = {t: [c["name"] for c in d["cols"] if "PK" in c["key"]] for t, d in tables.items()}

FALLBACK = {"child_id": ("app", "children", "id"),
            "org_id": ("app", "organisations", "id"),
            "therapist_user_id": ("app", "users", "id")}

def resolve_fk(tkey, col):
    refs = [r for r in col["refs"] if (r[0], r[1]) in tables]
    for s, t, c in refs:
        if pk[(s, t)] == [c]:
            return (s, t, c)
    if col["name"] in FALLBACK and "FK" in col["key"]:
        return FALLBACK[col["name"]]
    return None

# deviations for email/password login (the document uses phone OTP)
for c in tables[("app", "users")]["cols"]:
    if c["name"] == "email":
        c["nullable"] = False
        c["key"] = "UK"
tables[("app", "users")]["cols"].append({
    "name": "password_hash", "type": "text", "nullable": False, "key": "", "refs": [],
    "note": "AWAAZ DEVIATION: email + password login instead of phone OTP"})

TYPES = {
    "uuid": "UUID(as_uuid=True)", "text": "Text", "boolean": "Boolean",
    "smallint": "SmallInteger", "integer": "Integer", "bigint": "BigInteger",
    "date": "Date", "bytea": "LargeBinary", "jsonb": "JSONB",
    "timestamp with time zone": "DateTime(timezone=True)", "interval": "Interval",
    "text[]": "ARRAY(Text)", "smallint[]": "ARRAY(SmallInteger)",
}
def sa_type(t):
    if t in TYPES: return TYPES[t]
    m = re.match(r"numeric\((\d+),(\d+)\)", t)
    if m: return f"Numeric({m.group(1)}, {m.group(2)})"
    if t == "numeric": return "Numeric"
    m = re.match(r"character\((\d+)\)", t)
    if m: return f"CHAR({m.group(1)})"
    raise ValueError(f"unmapped type {t}")

IRREG = {"children": "Child", "policies": "Policy", "access_log": "AccessLog",
         "change_log": "ChangeLog", "settings": "Setting", "disciplines": "Discipline",
         "languages": "Language", "age_bands": "AgeBand", "organisations": "Organisation"}
def cls_name(schema, name):
    if name in IRREG: base = IRREG[name]
    else:
        parts = name.split("_")
        last = parts[-1]
        if last.endswith("ies"): last = last[:-3] + "y"
        elif last.endswith("ss") or last.endswith("us"): pass
        elif last.endswith("s"): last = last[:-1]
        parts[-1] = last
        base = "".join(p.capitalize() for p in parts)
    return base if schema == "app" else schema.capitalize() + base

NOW = {"created_at", "updated_at", "received_at"}
RESERVED = {"metadata", "registry"}

# dependency check / ordering
deps = defaultdict(set)
for t, d in tables.items():
    for c in d["cols"]:
        fk = resolve_fk(t, c)
        if fk and (fk[0], fk[1]) != t:
            deps[t].add((fk[0], fk[1]))
order, seen, temp = [], set(), set()
def visit(t):
    if t in seen: return
    if t in temp: raise SystemExit(f"CYCLE at {t}")
    temp.add(t)
    for d in sorted(deps[t]): visit(d)
    temp.discard(t); seen.add(t); order.append(t)
for t in sorted(tables): visit(t)

o = []
o.append('"""AUTO-GENERATED by generate_models.py from Awaaz_Database_Schema.md.\n\n'
         'Edit the generator (or add relationships in a separate file), not this one.\n"""\n')
o.append("from sqlalchemy import (BigInteger, Boolean, CHAR, Date, DateTime, ForeignKey, Integer,\n"
         "                        Interval, LargeBinary, Numeric, SmallInteger, Text, UniqueConstraint,\n"
         "                        text, func)")
o.append("from sqlalchemy.dialects.postgresql import ARRAY, JSONB, UUID")
o.append("from sqlalchemy.orm import mapped_column\n")
o.append("from db.session import Base\n")

fk_count = 0
used_cls = {}
for t in order:
    d = tables[t]
    schema, name = t
    cn = cls_name(schema, name)
    assert cn not in used_cls, f"class clash {cn}"
    used_cls[cn] = t
    o.append(f"\nclass {cn}(Base):")
    o.append(f'    __tablename__ = "{name}"')
    targs = []
    for u in d["uniques"]:
        targs.append("UniqueConstraint(" + ", ".join(f'"{x}"' for x in u) + ")")
    targs.append(f'{{"schema": "{schema}"}}')
    o.append("    __table_args__ = (" + ", ".join(targs) + ",)")
    o.append("")
    for c in d["cols"]:
        args = [sa_type(c["type"])]
        fk = resolve_fk(t, c)
        if fk:
            args.append(f'ForeignKey("{fk[0]}.{fk[1]}.{fk[2]}")')
            fk_count += 1
        kw = []
        is_pk = "PK" in c["key"]
        if is_pk:
            kw.append("primary_key=True")
            if c["type"] == "uuid" and len(pk[t]) == 1:
                kw.append('server_default=text("gen_random_uuid()")')
            elif c["type"] != "bigint" or len(pk[t]) > 1:
                kw.append("autoincrement=False")
        else:
            kw.append(f"nullable={c['nullable']}")
        if "UK" in c["key"] and not is_pk:
            kw.append("unique=True")
        elif fk and not is_pk:
            kw.append("index=True")
        if c["name"] in NOW and not c["nullable"]:
            kw.append("server_default=func.now()")
        attr = c["name"] + ("_" if c["name"] in RESERVED else "")
        dbname = f'"{c["name"]}", ' if attr != c["name"] else ""
        note = f'  # {c["note"]}' if c.get("note") else ""
        o.append(f"    {attr} = mapped_column({dbname}{', '.join(args + kw)}){note}")

o.append("\n\nSCHEMAS = " + repr(sorted({s for s, _ in tables})))
open(out, "w", encoding="utf-8").write("\n".join(o) + "\n")
print(f"wrote {out}: {len(order)} tables, {fk_count} single-column FKs")
print("views skipped:", len(views))